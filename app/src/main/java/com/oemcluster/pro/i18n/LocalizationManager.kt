    TR("tr", "Türkçe", "🇹🇷"),
    EN("en", "English", "🇬🇧"),
    DE("de", "Deutsch", "🇩🇪"),
    IT("it", "Italiano", "🇮🇹"),
    ES("es", "Español", "🇪🇸"),
    FR("fr", "Français", "🇫🇷"),
    JA("ja", "日本語", "🇯🇵"),
    PT("pt", "Português", "🇵🇹"),
    RU("ru", "Русский", "🇷🇺");

    companion object {
        fun fromCode(code: String): AppLanguage =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) } ?: TR
    }
}

